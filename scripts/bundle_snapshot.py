"""Reproduce the small offline bundle from the existing public dataset edition.

Run with the path to the source release directory. No source requests, revisions
or private platform exports are used. The ZIP contains only named public files.
"""

import hashlib
import json
from pathlib import Path
import sys
import zipfile

source = Path(sys.argv[1])
root = Path(__file__).resolve().parents[1]
destination = root / "packages/us-bank-data/src/usbankdata"
manifest = json.loads((source / "manifest.json").read_text())
assert manifest["release"] == "2026-q2-r1" and manifest["record_count"] == 4313
names = [
    "manifest.json",
    "financials.json",
    "README.txt",
    *[item["file"] for item in manifest["sources"]],
]
for item in [
    *[item for item in manifest["files"] if item["file"] == "financials.json"],
    *manifest["sources"],
]:
    assert hashlib.sha256((source / item["file"]).read_bytes()).hexdigest() == item["sha256"]
resource = destination / "resources/2026-q2-r1.zip"
resource.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(resource, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as bundle:
    for name in names:
        info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        bundle.writestr(info, (source / name).read_bytes(), compresslevel=9)
descriptor = {
    manifest["release"]: {
        "file": resource.name,
        "report_date": manifest["report_date"],
        "sha256": hashlib.sha256(resource.read_bytes()).hexdigest(),
    }
}
(destination / "_editions.py").write_text(
    '"""Pinned public edition checksums; generated by scripts/bundle_snapshot.py."""\n\nEDITIONS = '
    + repr(descriptor)
    + "\n"
)
print(json.dumps({"bundle_bytes": resource.stat().st_size, "editions": descriptor}))
